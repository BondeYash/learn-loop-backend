import { Router } from "express";
import { param } from "express-validator";
import rateLimit from "express-rate-limit";
import { protect, authorize } from "../middleware/auth.js";
import { validate } from "../validators/authValidators.js";
import { limitNoteUploads, parseNoteUpload } from "../middleware/noteUpload.js";
import * as c from "../controllers/doubtController.js";
const r = Router(), ids = (...names) => [...names.map(name => param(name).isMongoId()), validate];
const pace = rateLimit({ windowMs: 60000, max: 20, keyGenerator: req => String(req.user._id), standardHeaders: true, legacyHeaders: false, message: { message: "Please wait a moment before asking another doubt." } });
r.use("/admin/doubt-dost", protect, authorize("admin"));
r.get("/admin/doubt-dost", c.adminOverview);
r.put("/admin/doubt-dost/settings", c.saveSettings);
r.get("/admin/doubt-dost/activity", c.activity);
r.get("/admin/doubt-dost/courses/:courseId/documents", ...ids("courseId"), c.listDocuments);
r.post("/admin/doubt-dost/courses/:courseId/documents", ...ids("courseId"), limitNoteUploads, parseNoteUpload, c.uploadDocument);
r.put("/admin/doubt-dost/courses/:courseId/documents/:documentId", ...ids("courseId", "documentId"), c.updateDocument);
r.delete("/admin/doubt-dost/courses/:courseId/documents/:documentId", ...ids("courseId", "documentId"), c.removeDocument);
r.post("/admin/doubt-dost/courses/:courseId/preview", ...ids("courseId"), pace, c.askDoubt);
r.get("/courses/:courseId/doubt-dost", protect, authorize("student"), ...ids("courseId"), c.studentChat);
r.post("/courses/:courseId/doubt-dost", protect, authorize("student"), ...ids("courseId"), pace, c.askDoubt);
r.put("/courses/:courseId/doubt-dost/:turnId/feedback", protect, authorize("student"), ...ids("courseId", "turnId"), c.feedback);
r.get("/courses/:courseId/doubt-dost/documents/:documentId/url", protect, authorize("student", "admin"), ...ids("courseId", "documentId"), c.documentLink);
export default r;
